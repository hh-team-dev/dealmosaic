#!/usr/bin/env node
/**
 * Build-time technical SEO generator.
 *
 * Produces, into apps/web/public so Vite copies them into dist:
 *   - sitemap.xml        every durable public URL, with real lastmod dates
 *   - robots.txt         crawl policy plus explicit AI-crawler rules
 *   - llms.txt           a plain-language map for AI answer engines
 *
 * What it deliberately does NOT do: invent URLs for pages that do not exist,
 * or list search-result pages (they are query variants of one screen and would
 * be thin duplicate content).
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PRODUCTS } from '../apps/api/src/db/catalog-data.ts';

const SITE = process.env.SITE_URL ?? 'https://dealmosaic.pages.dev';
const here = dirname(fileURLToPath(import.meta.url));
const publicDir = join(here, '..', 'apps', 'web', 'public');
mkdirSync(publicDir, { recursive: true });

const today = new Date().toISOString().slice(0, 10);

/* ---------------------------------------------------------------- */
/* URLs                                                              */
/* ---------------------------------------------------------------- */

const staticPages = [
  { path: '/stays', changefreq: 'weekly', priority: '0.8', note: 'Hotel discovery, provider offers and entered-quote comparison' },
  { path: '/dining', changefreq: 'weekly', priority: '0.8', note: 'Restaurant and food-chain discovery, offer checks and bill calculator' },
  { path: '/', changefreq: 'daily', priority: '1.0', note: 'Landing' },
  { path: '/deals', changefreq: 'daily', priority: '0.95', note: 'Live coupons and deals' },
  { path: '/browse', changefreq: 'daily', priority: '0.9', note: 'Catalogue index' },
  { path: '/how-we-rank', changefreq: 'monthly', priority: '0.8', note: 'Methodology' },
  { path: '/data-sources', changefreq: 'weekly', priority: '0.7', note: 'Data provenance' },
  { path: '/disclosure', changefreq: 'yearly', priority: '0.3', note: 'Affiliate disclosure' },
  { path: '/privacy', changefreq: 'yearly', priority: '0.3', note: 'Privacy' },
  { path: '/terms', changefreq: 'yearly', priority: '0.3', note: 'Terms' },
  { path: '/contact', changefreq: 'yearly', priority: '0.4', note: 'Contact' },
];

const categories = [...new Map(PRODUCTS.map((p) => [p.categorySlug, p.category])).entries()].map(([slug, name]) => ({
  path: `/c/${slug}`,
  changefreq: 'weekly',
  priority: '0.7',
  note: `Category: ${name}`,
}));

const products = PRODUCTS.map((p) => ({
  path: `/p/${p.slug}`,
  changefreq: 'daily',
  priority: '0.8',
  note: p.title,
}));

const urls = [...staticPages, ...categories, ...products];

const escapeXml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-seo.mjs — do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls
  .map(
    (u) => `  <url>
    <loc>${escapeXml(SITE + u.path)}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${u.changefreq}</changefreq>
    <priority>${u.priority}</priority>
  </url>`,
  )
  .join('\n')}
</urlset>
`;

writeFileSync(join(publicDir, 'sitemap.xml'), sitemap, 'utf8');

/* ---------------------------------------------------------------- */
/* robots.txt                                                        */
/* ---------------------------------------------------------------- */

// Authenticated surfaces are private by definition; crawling them wastes crawl
// budget and can surface a signed-out redirect as a "page".
// NOTE: /search is deliberately NOT disallowed. It carries a `noindex` robots
// meta tag, and a crawler that is blocked by robots.txt can never read that tag —
// it would be indexed as an empty page instead of excluded properly.
const disallow = ['/app', '/app/', '/login', '/register', '/verify-email', '/forgot-password', '/reset-password'];

const robots = `# DEALMOSAIC — generated by scripts/generate-seo.mjs
User-agent: *
Allow: /
${disallow.map((d) => `Disallow: ${d}`).join('\n')}

# AI answer engines are welcome to read our public pages. We would rather be
# quoted accurately than be invisible.
User-agent: GPTBot
Allow: /
Disallow: /app

User-agent: ClaudeBot
Allow: /

User-agent: PerplexityBot
Allow: /

User-agent: Google-Extended
Allow: /

Sitemap: ${SITE}/sitemap.xml
`;

writeFileSync(join(publicDir, 'robots.txt'), robots, 'utf8');

/* ---------------------------------------------------------------- */
/* llms.txt — a map for AI answer engines                            */
/* ---------------------------------------------------------------- */

const llms = `# DEALMOSAIC

> DEALMOSAIC compares the true landed cost of a product across Indian stores —
> item price, delivery, fees and tax — and shows at most three ranked,
> commission-blind offers per variant. Tagline: "One search. Three real deals.
> Zero price surprises."

## What this site is
- A price-comparison service for India (INR, India-only at launch).
- Coverage includes electronics, books, fashion, and grocery/FMCG from Indian
  quick-commerce platforms (Blinkit, Zepto, Swiggy Instamart, BigBasket, JioMart,
  Flipkart Minutes, Amazon Now, DMart Ready).
- It does not sell anything. Every purchase happens on the retailer's own site.

## Facts worth quoting accurately
- Ranking inputs, in order: verification state of the total, stock, true landed
  total, match confidence, freshness. Affiliate commission is NEVER an input.
- An offer whose total cannot be fully verified can never be ranked first.
- Missing cost data is shown as unknown, never as zero.
- Deal Confidence (0-100) measures trust in the DATA, not product quality.
  Published weights: source 30%, freshness 25%, match 20%, delivery 15%,
  seller information 10%.
- Prices are observations with a timestamp, not offers, and vary by pincode for
  quick-commerce.

## Data provenance (important)
DEALMOSAIC does not scrape retailers and does not bypass bot protection. Where no
authorised feed exists, no price is shown. In the current build the comparison
catalogue is DEMONSTRATION DATA and is labelled as such in the interface.
See ${SITE}/data-sources for the live connector status of every platform.

## Pages
- ${SITE}/ — product overview
- ${SITE}/deals — verified coupons and deals
- ${SITE}/browse — every product compared
- ${SITE}/how-we-rank — the ranking rules in full
- ${SITE}/data-sources — connector status and access routes
- ${SITE}/disclosure — affiliate disclosure

## Contact
${SITE}/contact
`;

writeFileSync(join(publicDir, 'llms.txt'), llms, 'utf8');

console.log(`[seo] sitemap.xml: ${urls.length} URLs (${staticPages.length} static, ${categories.length} categories, ${products.length} products)`);
console.log('[seo] robots.txt and llms.txt written');
